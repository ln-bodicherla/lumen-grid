#!/usr/bin/env python3
"""Obsidian in one color: write a CSS snippet that sets every text color (body, muted,
links, headings, tags, code) to shades of the current theme accent, and enable it in
every vault Obsidian knows about. Obsidian reloads snippets live. Run by the theme-set
hook, so Program / Overload switching carries over; vaults created later get it on the next
theme switch or install."""
import json
import os
import re

HOME = os.path.expanduser("~")
COLORS = f"{HOME}/.local/state/omarchy/current/theme/colors.toml"
NAME = "lumen-mono"


def accent():
    try:
        m = re.search(r'^accent\s*=\s*"#([0-9A-Fa-f]{6})"', open(COLORS).read(), re.M)
        return "#" + m.group(1) if m else "#8ED7E6"
    except OSError:
        return "#8ED7E6"


def vaults():
    for cfg in (f"{HOME}/.config/obsidian/obsidian.json", f"{HOME}/.var/app/md.obsidian.Obsidian/config/obsidian/obsidian.json"):
        try:
            for v in json.load(open(cfg)).get("vaults", {}).values():
                if os.path.isdir(v.get("path", "")):
                    yield v["path"]
        except (OSError, ValueError):
            pass


def css(c):
    return f"""/* Lumen one-color text (generated by ~/lumen-grid/os/make-obsidian.py; theme accent {c}) */
body {{
  --lumen: {c};
  --text-normal: var(--lumen);
  --text-muted: color-mix(in srgb, var(--lumen) 70%, transparent);
  --text-faint: color-mix(in srgb, var(--lumen) 45%, transparent);
  --text-accent: var(--lumen);
  --text-accent-hover: color-mix(in srgb, var(--lumen) 80%, white);
  --link-color: var(--lumen);
  --link-color-hover: color-mix(in srgb, var(--lumen) 80%, white);
  --link-external-color: var(--lumen);
  --link-unresolved-color: color-mix(in srgb, var(--lumen) 60%, transparent);
  --tag-color: var(--lumen);
  --code-normal: var(--lumen);
  --interactive-accent: var(--lumen);
  --h1-color: var(--lumen); --h2-color: var(--lumen); --h3-color: var(--lumen);
  --h4-color: var(--lumen); --h5-color: var(--lumen); --h6-color: var(--lumen);
  --bold-color: color-mix(in srgb, var(--lumen) 85%, white);
  --italic-color: var(--lumen);
}}
.cm-s-obsidian span, .markdown-rendered code, .markdown-rendered pre {{ color: var(--lumen) !important; }}
"""


def main():
    c = accent()
    for vault in vaults():
        obs = os.path.join(vault, ".obsidian")
        os.makedirs(os.path.join(obs, "snippets"), exist_ok=True)
        with open(os.path.join(obs, "snippets", f"{NAME}.css"), "w") as f:
            f.write(css(c))
        appearance = os.path.join(obs, "appearance.json")
        try:
            data = json.load(open(appearance))
        except (OSError, ValueError):
            data = {}
        snippets = data.setdefault("enabledCssSnippets", [])
        if NAME not in snippets:
            snippets.append(NAME)
            json.dump(data, open(appearance, "w"), indent=2)


if __name__ == "__main__":
    main()
