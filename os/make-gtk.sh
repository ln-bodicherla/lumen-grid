#!/bin/bash
# Write GTK 3 / GTK 4 (libadwaita) color overrides in the current Omarchy theme colors, so
# Nautilus and other GTK apps get near-black surfaces, theme text and accent highlights.
# Run by the Omarchy theme-set hook so Program/Overload recolors it. Only files carrying the
# marker below are overwritten; any other gtk.css is backed up once to gtk.css.orig.
set -euo pipefail

COLORS="$HOME/.local/state/omarchy/current/theme/colors.toml"
MARK="/* lumen-grid: generated by ~/lumen-grid/os/make-gtk.sh */"
get() { grep -E "^$1[[:space:]]*=" "$COLORS" 2>/dev/null | head -1 | sed -E 's/.*"(#[0-9A-Fa-f]{6})".*/\1/'; }

accent=$(get accent); accent=${accent:-#8ED7E6}
orange=$(get orange); orange=${orange:-#d19a66}
fg=$(get foreground); fg=${fg:-#d6f4fa}
dimfg=$(get dark_foreground); dimfg=${dimfg:-#5f7a80}
sel=$(get selection); sel=${sel:-#24363b}
red=$(get red); red=${red:-#e06c75}
green=$(get green); green=${green:-#7fd6b8}
yellow=$(get yellow); yellow=${yellow:-#e5c07b}
win="#121212"; view="#0d0d0d"; card="#171717"; head="#0d0d0d"; side="#101010"; popover="#151515"

# libadwaita (GTK 4) reads CSS variables; GTK 3 Adwaita reads named colors
gtk4() { cat <<EOF
$MARK
:root {
  --accent-color: $accent;
  --accent-bg-color: $accent;
  --accent-fg-color: $view;
  --destructive-color: $red;
  --destructive-bg-color: $red;
  --destructive-fg-color: $view;
  --success-color: $green;
  --warning-color: $yellow;
  --error-color: $red;
  --window-bg-color: $win;
  --window-fg-color: $fg;
  --view-bg-color: $view;
  --view-fg-color: $fg;
  --headerbar-bg-color: $head;
  --headerbar-fg-color: $fg;
  --headerbar-backdrop-color: $head;
  --headerbar-shade-color: alpha($accent, 0.35);
  --sidebar-bg-color: $side;
  --sidebar-fg-color: $fg;
  --sidebar-backdrop-color: $side;
  --sidebar-shade-color: alpha($accent, 0.18);
  --secondary-sidebar-bg-color: $side;
  --secondary-sidebar-fg-color: $fg;
  --card-bg-color: $card;
  --card-fg-color: $fg;
  --dialog-bg-color: $win;
  --dialog-fg-color: $fg;
  --popover-bg-color: $popover;
  --popover-fg-color: $fg;
  --thumbnail-bg-color: $card;
  --thumbnail-fg-color: $fg;
  --border-color: alpha($accent, 0.22);
}

/* thin light line under header bars, the way Lumen panels are edged */
headerbar { box-shadow: inset 0 -1px alpha($accent, 0.35); }
/* selected rows and files: dark teal fill with an accent edge, not a solid block */
row:selected, .navigation-sidebar row:selected, gridview > child:selected, columnview row:selected {
  background-color: $sel; color: $fg; box-shadow: inset 2px 0 $accent;
}
/* attention / suggested actions use the theme's second color */
button.suggested-action { background-color: $orange; color: $view; }
EOF
}

gtk3() { cat <<EOF
$MARK
@define-color accent_color $accent;
@define-color accent_bg_color $accent;
@define-color accent_fg_color $view;
@define-color theme_selected_bg_color $sel;
@define-color theme_selected_fg_color $fg;
@define-color theme_bg_color $win;
@define-color theme_fg_color $fg;
@define-color theme_base_color $view;
@define-color theme_text_color $fg;
@define-color insensitive_fg_color $dimfg;
@define-color borders alpha($accent, 0.22);
@define-color window_bg_color $win;
@define-color window_fg_color $fg;
@define-color view_bg_color $view;
@define-color view_fg_color $fg;
@define-color headerbar_bg_color $head;
@define-color headerbar_fg_color $fg;
@define-color sidebar_bg_color $side;
@define-color card_bg_color $card;
@define-color popover_bg_color $popover;
@define-color error_color $red;
@define-color success_color $green;
@define-color warning_color $yellow;

headerbar, .titlebar { background: $head; box-shadow: inset 0 -1px alpha($accent, 0.35); }
EOF
}

write() {  # write <dir> <generator>
  local f="$HOME/.config/$1/gtk.css"
  mkdir -p "$(dirname "$f")"
  if [[ -f $f ]] && ! head -1 "$f" | grep -qF "$MARK" && [[ ! -f $f.orig ]]; then cp "$f" "$f.orig"; fi
  "$2" > "$f"
}
write gtk-4.0 gtk4
write gtk-3.0 gtk3
echo "GTK colors written in $accent"
