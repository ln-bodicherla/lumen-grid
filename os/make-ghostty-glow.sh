#!/bin/bash
# Write the Ghostty Lumen glow shader for the current Omarchy theme:
#  - light bloom: bright text bleeds a soft halo, like a Lumen display
#  - scanlines and a faint flicker, only on Overload and Redline (the darker programs)
#  - one color: everything (text, prompts, app colors, even 24-bit color) is tinted to
#    shades of the theme accent, so the terminal is all cyan / amber / red; the dark
#    background is left as it is
# Chained after the cursor trail in ~/.config/ghostty/config. Run by the theme-set hook.
set -euo pipefail

theme=$(cat "$HOME/.local/state/omarchy/current/theme.name" 2>/dev/null || echo lumen-program)
case $theme in
  lumen-overload|lumen-redline) scan=1.0 ;;
  *) scan=0.0 ;;
esac

COLORS="$HOME/.local/state/omarchy/current/theme/colors.toml"
hex=$(grep -E '^accent[[:space:]]*=' "$COLORS" 2>/dev/null | head -1 | sed -E 's/.*"#([0-9A-Fa-f]{6})".*/\1/')
hex=${hex:-8ED7E6}
rgb=$(awk -v r=$((16#${hex:0:2})) -v g=$((16#${hex:2:2})) -v b=$((16#${hex:4:2})) 'BEGIN { printf "%.3f, %.3f, %.3f", r / 255, g / 255, b / 255 }')

out="$HOME/.config/ghostty/shaders/lumen-glow.glsl"
mkdir -p "$(dirname "$out")"
cat > "$out" <<EOF
// Lumen display glow (generated by ~/lumen-grid/os/make-ghostty-glow.sh for $theme).
const float BLOOM = 0.55;      // halo strength
const float RADIUS = 2.6;      // halo reach in pixels
const float SCANLINES = $scan; // 1 on Overload / Redline
const vec3 ACCENT = vec3($rgb); // theme accent #$hex

// Map any color to a shade of the accent by its brightness; the dark background stays.
vec3 monochrome(vec3 c) {
  float lum = max(dot(c, vec3(0.2126, 0.7152, 0.0722)), max(c.r, max(c.g, c.b)) * 0.6);
  vec3 tint = ACCENT * clamp(lum * 1.25, 0.0, 1.0);
  tint = mix(tint, vec3(1.0), smoothstep(0.82, 1.0, lum) * 0.45);
  return mix(c, tint, smoothstep(0.11, 0.2, lum));
}

void mainImage(out vec4 fragColor, in vec2 fragCoord) {
  vec2 uv = fragCoord / iResolution.xy;
  vec4 base = texture(iChannel0, uv);
  base.rgb = monochrome(base.rgb);
  vec2 px = 1.0 / iResolution.xy;

  // 16-tap ring blur of the bright parts only, so the background stays black
  vec3 glow = vec3(0.0);
  for (int i = 0; i < 16; i++) {
    float a = float(i) * 0.3927;   // 2π / 16
    for (int r = 1; r <= 2; r++) {
      vec2 off = vec2(cos(a), sin(a)) * RADIUS * float(r) * px;
      vec3 c = monochrome(texture(iChannel0, uv + off).rgb);
      float lum = dot(c, vec3(0.2126, 0.7152, 0.0722));
      glow += c * smoothstep(0.25, 0.8, lum) / float(r);
    }
  }
  glow /= 24.0;
  vec3 color = base.rgb + glow * BLOOM;

  if (SCANLINES > 0.5) {
    float line = 0.88 + 0.12 * sin(fragCoord.y * 3.14159);
    float flicker = 0.985 + 0.015 * sin(iTime * 47.0);
    color *= line * flicker;
  }
  fragColor = vec4(color, base.a);
}
EOF
