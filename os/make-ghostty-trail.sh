#!/bin/bash
# Write the Ghostty Lumen shader in the current Omarchy theme accent:
#  - light-cycle cursor trail: when the cursor jumps (not plain typing), a light trail runs
#    from where it was to where it is and fades out in ~0.3s
#  - screensaver tint: Omarchy's screensaver is the only Ghostty window with a pure black
#    background (it sets it with OSC 11); there every pixel is recolored by brightness into
#    the theme accent, so its random effects come out cyan (Program) or amber (Overload)
# Run by the Omarchy theme-set hook so Program/Overload recolors it.
set -euo pipefail

COLORS="$HOME/.local/state/omarchy/current/theme/colors.toml"
hex=$(grep -E '^accent[[:space:]]*=' "$COLORS" 2>/dev/null | head -1 | sed -E 's/.*"#([0-9A-Fa-f]{6})".*/\1/')
hex=${hex:-8ED7E6}
rgb=$(awk -v r=$((16#${hex:0:2})) -v g=$((16#${hex:2:2})) -v b=$((16#${hex:4:2})) 'BEGIN { printf "%.3f, %.3f, %.3f", r / 255, g / 255, b / 255 }')

out="$HOME/.config/ghostty/shaders/lumen-trail.glsl"
mkdir -p "$(dirname "$out")"
cat > "$out" <<EOF
// Lumen light-cycle cursor trail (generated by ~/lumen-grid/os/make-ghostty-trail.sh; theme accent #$hex).
const vec3 LIGHT = vec3($rgb);
const float DURATION = 0.30;   // seconds the trail takes to fade

float segmentDistance(vec2 p, vec2 a, vec2 b) {
  vec2 pa = p - a, ba = b - a;
  float h = clamp(dot(pa, ba) / max(dot(ba, ba), 1e-4), 0.0, 1.0);
  return length(pa - ba * h);
}

bool isPureBlack(vec2 uv) {
  return all(lessThan(texture(iChannel0, uv).rgb, vec3(0.004)));
}

void mainImage(out vec4 fragColor, in vec2 fragCoord) {
  vec4 base = texture(iChannel0, fragCoord / iResolution.xy);
  fragColor = base;

  // Screensaver: all four corners pure black (normal terminals use the theme background).
  vec2 px = 1.5 / iResolution.xy;
  if (isPureBlack(px) && isPureBlack(vec2(1.0 - px.x, px.y)) &&
      isPureBlack(vec2(px.x, 1.0 - px.y)) && isPureBlack(1.0 - px)) {
    float lum = dot(base.rgb, vec3(0.2126, 0.7152, 0.0722));
    float level = clamp(max(lum, max(base.r, max(base.g, base.b))) * 1.15, 0.0, 1.0);
    vec3 tinted = mix(LIGHT * level, mix(LIGHT, vec3(1.0), 0.35), smoothstep(0.88, 1.0, level));
    fragColor = vec4(tinted, base.a);
    return;
  }

  // cursor rects are x, y (top-left, GL coordinates), width, height
  vec2 cur = iCurrentCursor.xy + vec2(iCurrentCursor.z, -iCurrentCursor.w) * 0.5;
  vec2 prev = iPreviousCursor.xy + vec2(iPreviousCursor.z, -iPreviousCursor.w) * 0.5;
  float fade = 1.0 - clamp((iTime - iTimeCursorChange) / DURATION, 0.0, 1.0);
  float jump = distance(cur, prev);

  // no trail for ordinary typing (one or two cells) or once it has faded
  if (fade <= 0.0 || jump < iCurrentCursor.z * 2.5) return;

  // the tail chases the cursor while the light fades
  vec2 tail = mix(prev, cur, 1.0 - fade);
  float d = segmentDistance(fragCoord, tail, cur);
  float h = iCurrentCursor.w;
  float core = smoothstep(h * 0.16, 0.0, d);
  float glow = smoothstep(h * 0.95, 0.0, d) * 0.35;
  vec2 run = cur - tail;
  float along = clamp(dot(fragCoord - tail, run) / max(dot(run, run), 1.0), 0.0, 1.0);
  float a = clamp((core + glow) * fade * (0.25 + 0.75 * along), 0.0, 1.0);
  fragColor = vec4(mix(base.rgb, LIGHT, a), base.a);
}
EOF
echo "Ghostty trail shader written in #$hex -> $out"
